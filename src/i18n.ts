export const text = (lang: Language) => (lang === "tr" ? tr : en);
export type Copy = typeof tr;
export function errorText(code: string, t: Copy) {
  return code === "locked"
    ? t.locked
    : code === "conflict"
      ? t.conflict
      : code === "import-conflict"
        ? t.importConflict
        : ["invalid-backup", "unknown-task"].includes(code)
          ? t.invalid
          : code === "unavailable"
            ? t.unavailable
            : t.storage;
}
export const number = (n: number, lang: Language) =>
  new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    maximumFractionDigits: 1,
  }).format(n);
